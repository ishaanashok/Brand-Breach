// Moves hunts kept in the older file store into the actors, cases under their brand. Safe to run again: what's there stays.
// Needs `bun run dev:actors` and `bun run generate`. Only reads the older data, and never changes it.
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { caseId } from '../src/core/case-id'
import type { BrandState } from '../src/core/machines/brand'
import type { CaseState } from '../src/core/machines/case'
import type { HuntState } from '../src/core/machines/hunt'
import { slug } from '../src/core/types'
import { wellFormed } from '../src/store/actors'
// @ts-ignore generated by `bun run generate`
import { actors } from '../generated/index.js'

const BATCH = 200
const dir = process.argv[2] ?? '.customs/live/actors'
const SOURCE = 'file-store'
const all = readdirSync(dir).filter(f => f.endsWith('.json')).map(f => ({ key: decodeURIComponent(f.slice(0, -5)), path: join(dir, f) }))
const read = <T>(path: string): T => JSON.parse(readFileSync(path, 'utf8'))
const ofKind = (kind: string) => all.filter(f => f.key.startsWith(`${kind}:`))

/** The dev server restarts whenever a source file changes. */
async function settled<T>(call: () => Promise<T>): Promise<T> {
  for (let tries = 0; ; tries++) {
    try { return await call() } catch (err) {
      if (tries >= 30 || !/unavailable|restarting|ECONNREFUSED/i.test(String(err))) throw err
      await Bun.sleep(2000)
    }
  }
}

async function adoptCases(brandSlug: string, cases: CaseState[]) {
  let added = 0
  for (let i = 0; i < cases.length; i += BATCH) added += await settled(() => actors.Brand.get(brandSlug).adoptCases(wellFormed(cases.slice(i, i + BATCH))))
  return added
}

// The older file store, with each case given the id it would have today.
const renamed = new Map<string, string>()
const byBrand = new Map<string, CaseState[]>()
for (const f of ofKind('case')) {
  const c = read<CaseState>(f.path)
  if (!c.hit?.url || !c.brand) continue
  const id = caseId(c.brand, c.hit.url)
  renamed.set(c.id, id)
  byBrand.set(c.brand, [...(byBrand.get(c.brand) ?? []), { ...c, id }])
}
let fileCases = 0
for (const [brandSlug, cases] of byBrand) fileCases += await adoptCases(brandSlug, cases)

const swap = (id: string) => renamed.get(id) ?? id
let fileHunts = 0
for (const f of ofKind('hunt')) {
  const h = read<HuntState>(f.path)
  if (!h.input) continue
  // Nothing is running these any more, and a restart must not pick them up.
  const status = h.status === 'budget_exhausted' ? h.status : 'done'
  const moved: HuntState = {
    ...h, status,
    caseIds: [...new Set(h.caseIds.map(swap))],
    spawns: (h.spawns ?? []).map(s => ({ ...s, caseId: swap(s.caseId) })),
  }
  if (await settled(() => actors.Hunt.get(h.id).adopt(wellFormed(moved)))) fileHunts++
}
for (const f of ofKind('brand')) {
  const b = read<BrandState>(f.path)
  const brandSlug = b.slug || slug(f.key.slice('brand:'.length))
  await settled(() => actors.Brand.get(brandSlug).adopt(SOURCE, wellFormed({
    ...b,
    slug: brandSlug,
    labels: (b.labels ?? []).map(l => ({ ...l, caseId: swap(l.caseId) })),
  })))
}
const playbook = ofKind('playbook')[0]
if (playbook) await settled(() => actors.Playbook.get('global').adopt(SOURCE, read(playbook.path)))
console.log(`files: ${fileCases} cases, ${fileHunts} hunts, ${ofKind('brand').length} brands`)
process.exit(0)
