import { caseBrand } from '../core/case-id'
import type { CaseState } from '../core/machines/case'
import type { BrandClient, CaseClient, HuntClient, PlaybookClient, Store } from './types'

/** Web text cut mid-character can't cross the wire as JSON, and one bad page must not lose its case. */
export function wellFormed<T>(value: T): T {
  if (typeof value === 'string') return value.toWellFormed() as T
  if (Array.isArray(value)) return value.map(wellFormed) as T
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, wellFormed(v)])) as T
  return value
}

/** Binds the generated Durable Actors client. Imported lazily so tests and offline runs need no runtime. */
export async function actorStore(): Promise<Store> {
  // @ts-ignore generated by `bun run generate`
  const { actors } = await import('../../generated/index.js')
  const kase = (id: string): CaseClient => {
    const client: any = actors.Brand.get(caseBrand(id))
    return new Proxy({}, { get: (_, method: string) => (...args: unknown[]) => client.caseCall(id, method, wellFormed(args)) }) as CaseClient
  }
  // One call per actor: reading each case alone runs a machine out of local ports within minutes.
  const cases = async (ids: string[]): Promise<CaseState[]> => {
    const byBrand = new Map<string, string[]>()
    for (const id of ids) {
      const slug = caseBrand(id)
      byBrand.set(slug, [...(byBrand.get(slug) ?? []), id])
    }
    const found = new Map<string, CaseState>()
    await Promise.all([...byBrand].map(async ([slug, keys]) => {
      const states: CaseState[] = await actors.Brand.get(slug).caseSnapshots(keys)
      keys.forEach((k, i) => found.set(k, states[i]!))
    }))
    return ids.map(id => found.get(id)!)
  }
  return {
    hunt: id => actors.Hunt.get(id) as HuntClient,
    kase,
    cases,
    brand: s => actors.Brand.get(s) as BrandClient,
    playbook: () => actors.Playbook.get('global') as PlaybookClient,
  }
}
